"""State-matched barrier interventions for E03 S09.

The S05 graph is a finite structural opportunity graph, whereas E01 replay uses
scenario-keyed counter-addressed streams.  S09 therefore uses a typed external
schedule: actor and Bubble-side tokens are generated by the frozen E01 SHA-256
RNG under a pairing key shared by every arm.  Transition construction,
validation, commit, cost, terminal precedence, and event serialization remain
the authoritative E01 implementations.
"""

